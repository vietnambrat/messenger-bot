"""Правила автоответов: (ключевые слова, варианты ответа) + варианты по умолчанию.

Для каждого правила — несколько вариантов фраз, из них случайно выбирается
одна, чтобы бот не отвечал всем одинаковым шаблоном.
"""

import random

RULES = [
    (["привет", "здравствуй", "хай", "добрый день", "добрый вечер"], [
        "Привет! Чем могу помочь?",
        "Здравствуйте! Слушаю вас.",
        "Привет, на связи! Что подсказать?",
    ]),
    (["цена", "стоимость", "сколько стоит"], [
        "По ценам лучше уточнить у менеджера — скоро с вами свяжутся.",
        "Сейчас пришлём актуальные цены, чуть позже свяжемся.",
        "По стоимости подскажем отдельно — ждите, скоро ответим.",
    ]),
    (["часы работы", "график работы", "во сколько"], [
        "Работаем с 9:00 до 18:00, пн-пт.",
        "График у нас: пн-пт, с 9 до 18.",
    ]),
    (["спасибо", "благодарю"], [
        "Пожалуйста! Если что — пишите.",
        "Не за что, обращайтесь!",
        "Рады помочь :)",
    ]),
]

DEFAULT_REPLIES = [
    "Спасибо за сообщение, скоро ответим!",
    "Получили ваше сообщение, ответим в ближайшее время.",
    "Спасибо, что написали! Скоро вернёмся с ответом.",
]


def get_reply(text: str) -> str:
    text_lower = text.lower()
    for keywords, replies in RULES:
        if any(keyword in text_lower for keyword in keywords):
            return random.choice(replies)
    return random.choice(DEFAULT_REPLIES)
