"""Правила автоответов: список (ключевые слова, ответ) + ответ по умолчанию."""

RULES = [
    (["привет", "здравствуй", "хай", "добрый день", "добрый вечер"],
     "Здравствуйте! Чем можем помочь?"),
    (["цена", "стоимость", "сколько стоит"],
     "Актуальные цены уточняйте у менеджера — скоро с вами свяжутся."),
    (["часы работы", "график работы", "во сколько"],
     "Мы работаем с 9:00 до 18:00, пн-пт."),
    (["спасибо", "благодарю"],
     "Пожалуйста! Обращайтесь, если будут ещё вопросы."),
]

DEFAULT_REPLY = "Спасибо за сообщение! Мы ответим вам в ближайшее время."


def get_reply(text: str) -> str:
    text_lower = text.lower()
    for keywords, reply in RULES:
        if any(keyword in text_lower for keyword in keywords):
            return reply
    return DEFAULT_REPLY
